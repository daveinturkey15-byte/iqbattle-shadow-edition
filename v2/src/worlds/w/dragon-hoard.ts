import { hash, wash, softBlob, wrap, type WorldDef } from './kit.ts';

export const WORLD: WorldDef = {
  id: 'dragon-hoard',
  align: 'bad',
  draw(c: CanvasRenderingContext2D, w: number, h: number, t: number): void {
    wash(c, w, h, '#15101d', '#040307');
    const breath = Math.sin((t * 2 * Math.PI) / 6000);
    const sway = Math.sin((t * 2 * Math.PI) / 9000 + 1.3);
    const drift = Math.sin((t * 2 * Math.PI) / 12500 + 0.6);
    const minDim = Math.min(w, h);
    softBlob(c, w * 0.08, h * 0.9, w * 0.34, h * 0.3, '184,124,42', 0.2 + 0.04 * breath);
    softBlob(c, w * 0.92, h * 0.88, w * 0.36, h * 0.32, '184,124,42', 0.2 - 0.04 * breath);
    softBlob(c, w * 0.5, h * 0.08, w * 0.4, h * 0.22, '120,40,24', 0.12 + 0.03 * sway);
    softBlob(c, w * 0.5, h * 1.02, w * 0.6, h * 0.3, '90,58,18', 0.16);
    c.save();
    c.fillStyle = '#0a080e';
    c.beginPath();
    c.moveTo(0, 0);
    c.lineTo(w * 0.17, 0);
    c.bezierCurveTo(w * 0.13, h * 0.32, w * 0.1, h * 0.62, w * 0.05, h);
    c.lineTo(0, h);
    c.closePath();
    c.fill();
    c.restore();
    c.save();
    c.fillStyle = '#0a080e';
    c.beginPath();
    c.moveTo(w, 0);
    c.lineTo(w * 0.83, 0);
    c.bezierCurveTo(w * 0.87, h * 0.32, w * 0.9, h * 0.62, w * 0.95, h);
    c.lineTo(w, h);
    c.closePath();
    c.fill();
    c.restore();
    c.save();
    c.translate(w * 0.5, h * 0.44 + breath * minDim * 0.022);
    c.scale(1, 0.62 + 0.03 * breath);
    c.fillStyle = '#0d0a12';
    c.beginPath();
    c.ellipse(0, 0, w * 0.44, h * 0.38, 0, 0, Math.PI * 2);
    c.fill();
    c.restore();
    const eyeY = h * 0.3 + breath * minDim * 0.016;
    const eyeLX = w * 0.5 - minDim * 0.185 + sway * minDim * 0.012;
    const eyeRX = w * 0.5 + minDim * 0.185 + sway * minDim * 0.012;
    const pA = wrap(t, 5300) / 5300;
    const pB = wrap(t, 7100) / 7100;
    const dA = (pA - 0.68) / 0.035;
    const dB = (pB - 0.32) / 0.035;
    const openA = 1 - 0.93 * Math.exp(-dA * dA);
    const openB = 1 - 0.93 * Math.exp(-dB * dB);
    const flA = 0.8 + 0.2 * Math.sin((t * 2 * Math.PI) / 3400 + 1.0);
    const flB = 0.8 + 0.2 * Math.sin((t * 2 * Math.PI) / 4200 + 3.1);
    softBlob(c, eyeLX, eyeY, minDim * 0.1, minDim * 0.065, '255,122,28', 0.2 * flA + 0.06);
    softBlob(c, eyeRX, eyeY, minDim * 0.1, minDim * 0.065, '255,122,28', 0.2 * flB + 0.06);
    c.save();
    c.translate(eyeLX, eyeY);
    c.scale(1, Math.max(0.07, openA));
    c.fillStyle = '#3a1c08';
    c.beginPath();
    c.ellipse(0, 0, minDim * 0.045, minDim * 0.022, -0.12, 0, Math.PI * 2);
    c.fill();
    c.fillStyle = '#ff9a2e';
    c.beginPath();
    c.ellipse(0, 0, minDim * 0.03, minDim * 0.013, -0.12, 0, Math.PI * 2);
    c.fill();
    c.fillStyle = '#080303';
    c.beginPath();
    c.ellipse(0, 0, minDim * 0.005, minDim * 0.011, 0, 0, Math.PI * 2);
    c.fill();
    c.restore();
    c.save();
    c.translate(eyeRX, eyeY);
    c.scale(1, Math.max(0.07, openB));
    c.fillStyle = '#3a1c08';
    c.beginPath();
    c.ellipse(0, 0, minDim * 0.045, minDim * 0.022, 0.12, 0, Math.PI * 2);
    c.fill();
    c.fillStyle = '#ff9a2e';
    c.beginPath();
    c.ellipse(0, 0, minDim * 0.03, minDim * 0.013, 0.12, 0, Math.PI * 2);
    c.fill();
    c.fillStyle = '#080303';
    c.beginPath();
    c.ellipse(0, 0, minDim * 0.005, minDim * 0.011, 0, 0, Math.PI * 2);
    c.fill();
    c.restore();
    const moundCX = w * 0.5;
    const moundBY = h * 1.04;
    const moundRX = w * 0.58;
    const moundH = h * 0.36;
    const lift = breath * h * 0.013;
    c.save();
    c.translate(0, lift);
    const g = c.createLinearGradient(0, moundBY - moundH, 0, moundBY);
    g.addColorStop(0, '#6b4a18');
    g.addColorStop(0.45, '#3d2a10');
    g.addColorStop(1, '#120c06');
    c.fillStyle = g;
    c.beginPath();
    c.ellipse(moundCX, moundBY, moundRX, moundH * 0.52, 0, 0, Math.PI * 2);
    c.fill();
    for (let i = 0; i < 84; i++) {
      const hx = hash(11 + i * 7);
      const hy = hash(1011 + i * 7);
      const hz = hash(2011 + i * 7);
      const hw = hash(3011 + i * 7);
      const dx = hx * 2 - 1;
      const dome = 1 - dx * dx * 0.72;
      const px = moundCX + dx * moundRX * 0.92 + drift * minDim * 0.004 * dome;
      const py = moundBY - hy * moundH * dome * 0.92 - (1 - dome) * h * 0.02;
      const cr = minDim * 0.02 * (0.55 + 0.75 * hz) * (0.45 + 0.55 * dome);
      const dim = 0.42 + 0.58 * Math.min(1, Math.abs(dx) * 2.4 + 0.12);
      const r = Math.floor((118 + 72 * hz) * dim);
      const gg = Math.floor((82 + 58 * hw) * dim);
      const b = Math.floor((28 + 26 * hx) * dim);
      c.fillStyle = 'rgb(' + r + ',' + gg + ',' + b + ')';
      c.beginPath();
      c.ellipse(px, py, cr, cr * 0.38, (hw - 0.5) * 0.5, 0, Math.PI * 2);
      c.fill();
      c.strokeStyle = 'rgba(255,205,110,0.28)';
      c.lineWidth = 1;
      c.stroke();
      const tw = 0.5 + 0.5 * Math.sin((t * 2 * Math.PI) / 2600 + hx * 6.283);
      if (tw > 0.84) {
        c.fillStyle = 'rgba(255,235,170,0.7)';
        c.beginPath();
        c.ellipse(px - cr * 0.2, py - cr * 0.12, cr * 0.28, cr * 0.1, -0.3, 0, Math.PI * 2);
        c.fill();
      }
    }
    for (let k = 0; k < 3; k++) {
      const span = w * 1.2;
      const speed = w / (10800 + k * 2600);
      const gx = wrap(hash(9000 + k) * span + t * speed, span) - w * 0.1;
      const gy = moundBY - moundH * (0.3 + hash(9100 + k) * 0.35);
      softBlob(c, gx, gy, minDim * 0.07, minDim * 0.028, '255,220,130', 0.2);
      c.fillStyle = 'rgba(255,240,190,0.5)';
      c.beginPath();
      c.ellipse(gx, gy, minDim * 0.03, minDim * 0.006, -0.25, 0, Math.PI * 2);
      c.fill();
    }
    c.restore();
    for (let j = 0; j < 24; j++) {
      const ex = hash(5000 + j * 3) * w;
      const spanH = h + 90;
      const rise = h / 15000;
      const ey = h + 45 - wrap(hash(6000 + j * 3) * spanH + t * rise, spanH);
      const er = 1 + hash(7000 + j * 3) * 2.2;
      const flick = 0.5 + 0.5 * Math.sin((t * 2 * Math.PI) / 3800 + hash(8000 + j * 3) * 6.283);
      c.globalAlpha = 0.1 + 0.22 * flick * (1 - Math.abs(ex - w * 0.5) / w);
      c.fillStyle = j % 3 === 0 ? '#ffb54d' : '#8a6a3a';
      c.beginPath();
      c.arc(ex + sway * 8, ey, er, 0, Math.PI * 2);
      c.fill();
    }
    c.globalAlpha = 1;
    const vg = c.createRadialGradient(w / 2, h * 0.52, minDim * 0.08, w / 2, h * 0.52, Math.max(w, h) * 0.72);
    vg.addColorStop(0, 'rgba(2,2,6,0.58)');
    vg.addColorStop(0.55, 'rgba(2,2,6,0.2)');
    vg.addColorStop(1, 'rgba(0,0,0,0)');
    c.fillStyle = vg;
    c.fillRect(0, 0, w, h);
    c.globalAlpha = 1;
  },
};
