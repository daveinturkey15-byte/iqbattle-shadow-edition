import { hash, wash, softBlob, wrap, type WorldDef } from './kit.ts';

export const WORLD: WorldDef = {
  id: 'cave-crystal',
  align: 'neutral',
  draw(c: CanvasRenderingContext2D, w: number, h: number, t: number): void {
    wash(c, w, h, '#141e34', '#03060b');
    const minD = Math.min(w, h);
    const yPool = h * 0.78;
    const bases = ['#1d3248', '#233c55', '#1a2b44', '#25455e'];
    const tips = ['#8fd4e8', '#a9c6ff', '#9fe8d8', '#c2b8ff'];
    const slowA = 0.20 + 0.05 * Math.sin((t / 3400) * Math.PI * 2);
    const slowB = 0.18 + 0.05 * Math.sin((t / 4200) * Math.PI * 2 + 1.7);
    const slowC = 0.12 + 0.04 * Math.sin((t / 5100) * Math.PI * 2 + 3.1);
    softBlob(c, w * 0.02, h * 0.30, w * 0.30, h * 0.32, '96,180,225', slowA);
    softBlob(c, w * 0.98, h * 0.34, w * 0.30, h * 0.34, '130,140,235', slowB);
    softBlob(c, w * 0.12, h * 0.02, w * 0.26, h * 0.20, '90,160,210', slowC);
    softBlob(c, w * 0.88, h * 0.04, w * 0.26, h * 0.22, '150,120,220', slowC);
    softBlob(c, w * 0.06, yPool + (h - yPool) * 0.5, w * 0.22, h * 0.12, '70,140,180', 0.16);
    softBlob(c, w * 0.94, yPool + (h - yPool) * 0.5, w * 0.22, h * 0.12, '100,120,210', 0.16);
    c.globalAlpha = 1;
    for (let i = 0; i < 5; i++) {
      const hy = hash(900 + i) * h * 0.7;
      const hh = 10 + hash(910 + i) * 26;
      c.fillStyle = i % 2 === 0 ? 'rgba(18,28,46,0.55)' : 'rgba(12,19,33,0.55)';
      c.fillRect(0, hy, w, hh);
    }
    for (let i = 0; i < 14; i++) {
      const r0 = hash(100 + i * 5);
      const r1 = hash(101 + i * 5);
      const r2 = hash(102 + i * 5);
      const r3 = hash(103 + i * 5);
      const bx = -w * 0.03 + r1 * w * 0.05;
      const by = h * 0.06 + (i / 13) * h * 0.66 + (r2 - 0.5) * h * 0.05;
      const len = minD * (0.09 + r0 * 0.20);
      const wd = len * (0.26 + r3 * 0.18);
      const ph = r2 * Math.PI * 2;
      const ang = Math.PI / 2 + (r1 - 0.5) * 1.1 + 0.04 * Math.sin((t / 2900) * Math.PI * 2 + ph);
      const baseCol = bases[Math.floor(r0 * 4) % 4];
      const tipCol = tips[Math.floor(r3 * 4) % 4];
      c.save();
      c.translate(bx, by);
      c.rotate(ang);
      const g = c.createLinearGradient(0, 0, 0, -len);
      g.addColorStop(0, baseCol);
      g.addColorStop(0.55, '#2f5570');
      g.addColorStop(1, tipCol);
      c.fillStyle = g;
      c.beginPath();
      c.moveTo(-wd * 0.5, 0);
      c.lineTo(-wd * 0.18, -len * 0.72);
      c.lineTo(0, -len);
      c.lineTo(wd * 0.18, -len * 0.72);
      c.lineTo(wd * 0.5, 0);
      c.closePath();
      c.fill();
      c.strokeStyle = 'rgba(170,220,250,0.32)';
      c.lineWidth = 1;
      c.stroke();
      c.strokeStyle = 'rgba(200,240,255,0.26)';
      c.beginPath();
      c.moveTo(0, -4);
      c.lineTo(0, -len * 0.92);
      c.stroke();
      c.globalAlpha = 0.10 + 0.10 * (0.5 + 0.5 * Math.sin((t / 2600) * Math.PI * 2 + ph));
      c.fillStyle = tipCol;
      c.beginPath();
      c.moveTo(-wd * 0.14, -len * 0.78);
      c.lineTo(0, -len);
      c.lineTo(wd * 0.14, -len * 0.78);
      c.closePath();
      c.fill();
      c.restore();
    }
    for (let i = 0; i < 14; i++) {
      const r0 = hash(200 + i * 5);
      const r1 = hash(201 + i * 5);
      const r2 = hash(202 + i * 5);
      const r3 = hash(203 + i * 5);
      const bx = w * 1.03 - r1 * w * 0.05;
      const by = h * 0.08 + (i / 13) * h * 0.64 + (r2 - 0.5) * h * 0.05;
      const len = minD * (0.09 + r0 * 0.20);
      const wd = len * (0.26 + r3 * 0.18);
      const ph = r1 * Math.PI * 2;
      const ang = -Math.PI / 2 + (r1 - 0.5) * 1.1 + 0.04 * Math.sin((t / 3100) * Math.PI * 2 + ph);
      const baseCol = bases[Math.floor(r2 * 4) % 4];
      const tipCol = tips[Math.floor(r0 * 4) % 4];
      c.save();
      c.translate(bx, by);
      c.rotate(ang);
      const g = c.createLinearGradient(0, 0, 0, -len);
      g.addColorStop(0, baseCol);
      g.addColorStop(0.55, '#314f6a');
      g.addColorStop(1, tipCol);
      c.fillStyle = g;
      c.beginPath();
      c.moveTo(-wd * 0.5, 0);
      c.lineTo(-wd * 0.18, -len * 0.72);
      c.lineTo(0, -len);
      c.lineTo(wd * 0.18, -len * 0.72);
      c.lineTo(wd * 0.5, 0);
      c.closePath();
      c.fill();
      c.strokeStyle = 'rgba(170,220,250,0.32)';
      c.lineWidth = 1;
      c.stroke();
      c.globalAlpha = 0.10 + 0.10 * (0.5 + 0.5 * Math.sin((t / 2700) * Math.PI * 2 + ph + 2.0));
      c.fillStyle = tipCol;
      c.beginPath();
      c.moveTo(-wd * 0.14, -len * 0.78);
      c.lineTo(0, -len);
      c.lineTo(wd * 0.14, -len * 0.78);
      c.closePath();
      c.fill();
      c.restore();
    }
    for (let i = 0; i < 8; i++) {
      const r0 = hash(300 + i * 4);
      const r1 = hash(301 + i * 4);
      const r2 = hash(302 + i * 4);
      const left = i % 2 === 0;
      const bx = left ? w * (0.02 + r0 * 0.20) : w * (0.78 + r0 * 0.20);
      const by = -h * 0.02;
      const len = minD * (0.07 + r1 * 0.13);
      const wd = len * 0.32;
      const ph = r2 * Math.PI * 2;
      const ang = Math.PI + (r1 - 0.5) * 0.5 + 0.03 * Math.sin((t / 3800) * Math.PI * 2 + ph);
      c.save();
      c.translate(bx, by);
      c.rotate(ang);
      const g = c.createLinearGradient(0, 0, 0, -len);
      g.addColorStop(0, '#22364e');
      g.addColorStop(1, tips[Math.floor(r2 * 4) % 4]);
      c.fillStyle = g;
      c.beginPath();
      c.moveTo(-wd * 0.5, 0);
      c.lineTo(0, -len);
      c.lineTo(wd * 0.5, 0);
      c.closePath();
      c.fill();
      c.strokeStyle = 'rgba(175,225,250,0.28)';
      c.lineWidth = 1;
      c.stroke();
      c.restore();
    }
    const pg = c.createLinearGradient(0, yPool, 0, h);
    pg.addColorStop(0, '#0b1624');
    pg.addColorStop(0.35, '#070f1a');
    pg.addColorStop(1, '#020409');
    c.fillStyle = pg;
    c.fillRect(0, yPool, w, h - yPool);
    c.fillStyle = 'rgba(140,200,235,0.18)';
    c.fillRect(0, yPool, w, 1.5);
    for (let i = 0; i < 10; i++) {
      const r0 = hash(400 + i * 3);
      const r1 = hash(401 + i * 3);
      const edge = i % 2 === 0 ? r0 * w * 0.24 : w * (0.76 + r0 * 0.24);
      const len = minD * (0.03 + r1 * 0.06);
      const wd = len * 0.5;
      c.save();
      c.translate(edge, yPool + 2);
      const g = c.createLinearGradient(0, 0, 0, -len);
      g.addColorStop(0, '#1c3048');
      g.addColorStop(1, tips[Math.floor(r1 * 4) % 4]);
      c.fillStyle = g;
      c.beginPath();
      c.moveTo(-wd * 0.5, 0);
      c.lineTo(0, -len);
      c.lineTo(wd * 0.5, 0);
      c.closePath();
      c.fill();
      c.restore();
    }
    for (let k = 0; k < 5; k++) {
      const rx = hash(500 + k * 4);
      const rz = hash(501 + k * 4);
      const dx = w * (0.28 + rx * 0.44);
      const dy = yPool + (h - yPool) * (0.30 + rz * 0.55);
      const cycle = 4300 + rx * 2200;
      const off = rz * cycle;
      const p = wrap(t + off, cycle) / cycle;
      const rad = 6 + p * (26 + rx * 34);
      const al = (1 - p) * 0.32;
      c.strokeStyle = 'rgba(150,210,240,0.35)';
      c.lineWidth = 1.2;
      c.globalAlpha = al;
      c.beginPath();
      c.ellipse(dx, dy, rad, rad * 0.32, 0, 0, Math.PI * 2);
      c.stroke();
      c.globalAlpha = al * 0.5;
      c.beginPath();
      c.ellipse(dx, dy, rad * 0.55, rad * 0.18, 0, 0, Math.PI * 2);
      c.stroke();
      c.globalAlpha = 1;
    }
    for (let i = 0; i < 26; i++) {
      const r0 = hash(600 + i * 3);
      const r1 = hash(601 + i * 3);
      const r2 = hash(602 + i * 3);
      const speed = 0.008 + r2 * 0.008;
      const span = h + 40;
      const yy = wrap(r1 * span - t * speed, span) - 20;
      const xx = r0 * w + 0.02 * w * Math.sin((t / 3600) * Math.PI * 2 + r2 * 6.28);
      const s = 0.8 + r2 * 1.8;
      c.globalAlpha = 0.10 + r1 * 0.18;
      c.fillStyle = r0 < 0.5 ? '#9fd8ec' : '#b9c4f5';
      c.beginPath();
      c.arc(xx, yy, s, 0, Math.PI * 2);
      c.fill();
    }
    c.globalAlpha = 1;
    const vg = c.createRadialGradient(w * 0.5, h * 0.48, minD * 0.08, w * 0.5, h * 0.48, minD * 0.85);
    vg.addColorStop(0, 'rgba(3,6,11,0.62)');
    vg.addColorStop(0.55, 'rgba(3,6,11,0.38)');
    vg.addColorStop(1, 'rgba(3,6,11,0)');
    c.fillStyle = vg;
    c.fillRect(0, 0, w, h);
    c.globalAlpha = 1;
  },
};
